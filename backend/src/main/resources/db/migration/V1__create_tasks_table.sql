-- =====================================================================
-- V1: create the tasks table (Phase 1 - basic CRUD)
-- Matches the entity com.todoapp.entity.Task 1-1.
--
-- The file name follows the Flyway convention (V<version>__<description>.sql),
-- so in Phase 2 you only need to move this folder into
-- src/main/resources/db/migration and switch ddl-auto: update -> validate.
--
-- Run manually:
--   docker exec -i todo-postgres psql -U todo -d tododb < backend/db/V1__create_tasks_table.sql
-- =====================================================================

CREATE TABLE IF NOT EXISTS tasks (
    -- IDENTITY is the standard SQL way for Postgres to generate the primary key,
    -- matching @GeneratedValue(strategy = GenerationType.IDENTITY).
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- 255 matches @Size(max = 255) in TaskRequest.
    title       VARCHAR(255)  NOT NULL,
    description VARCHAR(2000),
    completed   BOOLEAN       NOT NULL DEFAULT FALSE,

    -- A Java Instant is an absolute point in time (UTC) -> use TIMESTAMPTZ,
    -- not TIMESTAMP (no time zone), to avoid clock skew between server and DB.
    created_at  TIMESTAMPTZ(6) NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ(6) NOT NULL DEFAULT now(),

    -- Reject whitespace-only titles at the DB level too (in case someone
    -- inserts directly, bypassing the API where @NotBlank already checks this).
    CONSTRAINT chk_tasks_title_not_blank CHECK (btrim(title) <> '')
);
